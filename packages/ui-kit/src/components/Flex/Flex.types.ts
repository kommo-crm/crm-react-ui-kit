/**
 * CSS `display` value of the container.
 */
export type FlexDisplay = 'flex' | 'inline-flex' | 'none';

/**
 * Direction of the main axis.
 */
export type FlexDirection = 'row' | 'column' | 'row-reverse' | 'column-reverse';

/**
 * Alignment of the items along the cross axis.
 */
export type FlexAlign = 'start' | 'center' | 'end' | 'baseline' | 'stretch';

/**
 * Distribution of the items along the main axis.
 */
export type FlexJustify = 'start' | 'center' | 'end' | 'between';

/**
 * Wrapping of the items onto multiple lines.
 */
export type FlexWrap = 'nowrap' | 'wrap' | 'wrap-reverse';
